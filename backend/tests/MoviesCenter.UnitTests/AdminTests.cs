using FluentAssertions;
using Moq;
using MoviesCenter.Application.Common.Interfaces;
using MoviesCenter.Application.Common.Models;
using MoviesCenter.Application.Features.Admin.Dtos;
using Xunit;

namespace MoviesCenter.UnitTests;

public class AdminTests
{
    private readonly Mock<IAdminService> _mockAdminService = new();

    [Fact]
    public async Task GetStatsOverview_ShouldReturnExpectedStats()
    {
        // Arrange
        var syncStatus = new TmdbSyncStatusDto(false, DateTimeOffset.UtcNow, "Success", 50, 0, "Admin");
        var expectedStats = new AdminStatsOverviewDto(
            TotalTitles: 120,
            TotalMovies: 80,
            TotalSeries: 40,
            TotalSources: 240,
            PendingReports: 2,
            TotalUsers: 15,
            LastSyncStatus: syncStatus
        );

        _mockAdminService
            .Setup(s => s.GetStatsOverviewAsync(It.IsAny<CancellationToken>()))
            .ReturnsAsync(expectedStats);

        // Act
        var result = await _mockAdminService.Object.GetStatsOverviewAsync();

        // Assert
        result.Should().BeEquivalentTo(expectedStats);
        result.TotalTitles.Should().Be(120);
        result.PendingReports.Should().Be(2);
    }

    [Fact]
    public async Task ToggleTitleFeatured_ShouldReturnTrueOnSuccess()
    {
        // Arrange
        _mockAdminService
            .Setup(s => s.ToggleTitleFeaturedAsync(10, It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        // Act
        var result = await _mockAdminService.Object.ToggleTitleFeaturedAsync(10);

        // Assert
        result.Should().BeTrue();
        _mockAdminService.Verify(s => s.ToggleTitleFeaturedAsync(10, It.IsAny<CancellationToken>()), Times.Once);
    }

    [Fact]
    public async Task CreateSource_ShouldReturnNewAdminSourceDto()
    {
        // Arrange
        var request = new CreateAdminSourceRequest(
            TitleId: 10,
            SeasonNumber: null,
            EpisodeNumber: null,
            ProviderName: "Custom Mirror",
            SourceType: "embed",
            Url: "https://custom.stream/embed/10",
            Quality: "1080p",
            Priority: 6,
            IsActive: true
        );

        var expectedDto = new AdminSourceDto(
            Id: 99,
            TitleId: 10,
            TitleName: "Interstellar",
            SeasonNumber: null,
            EpisodeNumber: null,
            SeasonEpisode: null,
            ProviderName: "Custom Mirror",
            SourceType: "embed",
            Url: "https://custom.stream/embed/10",
            Quality: "1080p",
            Priority: 6,
            IsActive: true,
            IsAutoGenerated: false,
            LastVerifiedAt: null,
            CreatedAt: DateTime.UtcNow
        );

        _mockAdminService
            .Setup(s => s.CreateSourceAsync(request, It.IsAny<CancellationToken>()))
            .ReturnsAsync(expectedDto);

        // Act
        var result = await _mockAdminService.Object.CreateSourceAsync(request);

        // Assert
        result.Should().BeEquivalentTo(expectedDto);
        result.Id.Should().Be(99);
        result.ProviderName.Should().Be("Custom Mirror");
    }

    [Fact]
    public async Task UpdateReportStatus_ShouldCallService()
    {
        // Arrange
        _mockAdminService
            .Setup(s => s.UpdateReportStatusAsync(5, "Resolved", It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        // Act
        var result = await _mockAdminService.Object.UpdateReportStatusAsync(5, "Resolved");

        // Assert
        result.Should().BeTrue();
        _mockAdminService.Verify(s => s.UpdateReportStatusAsync(5, "Resolved", It.IsAny<CancellationToken>()), Times.Once);
    }

    [Fact]
    public async Task CreateDirectUploadUrl_ShouldReturnEndpoint()
    {
        // Arrange
        var expectedUpload = new UploadUrlResponseDto("asset_123", "https://upload.url", "https://play.url", "ReadyForUpload", "Direct upload endpoint generated.");
        _mockAdminService
            .Setup(s => s.CreateDirectUploadUrlAsync("sample.mp4", "Sample Movie", It.IsAny<CancellationToken>()))
            .ReturnsAsync(expectedUpload);

        // Act
        var result = await _mockAdminService.Object.CreateDirectUploadUrlAsync("sample.mp4", "Sample Movie");

        // Assert
        result.Should().BeEquivalentTo(expectedUpload);
        result.AssetId.Should().Be("asset_123");
    }
}
