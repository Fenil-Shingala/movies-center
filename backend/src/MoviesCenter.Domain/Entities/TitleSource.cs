using MoviesCenter.Domain.Common;

namespace MoviesCenter.Domain.Entities;

public class TitleSource : BaseEntity
{
    public int TitleId { get; set; }
    public Title Title { get; set; } = null!;

    public int SourceProviderId { get; set; }
    public SourceProvider SourceProvider { get; set; } = null!;

    public int? SeasonNumber { get; set; }
    public int? EpisodeNumber { get; set; }
    public string? EmbedUrl { get; set; }
    public string? StreamUrl { get; set; }
    public string Quality { get; set; } = "1080p";
    public int Priority { get; set; } = 1;
    public bool IsAutoGenerated { get; set; } = false;
    public bool IsActive { get; set; } = true;
    public DateTime? LastVerifiedAt { get; set; }
}
